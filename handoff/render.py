"""Step 9: assemble KT-<dev>.md and kt.json.

The cited sections come straight from validated map notes, so the final
document contains no claim the validator has not checked. Cites become
links to the exact line (or commit) on GitHub at the analysed HEAD.
"""

import re

from handoff.validate import COMMIT_RE, LINE_RE


def _name(analysis: dict, dev_id: str | None) -> str:
    for d in analysis["developers"]:
        if d["id"] == dev_id:
            return d["names"][0]
    return dev_id or "none"


def _url(cite: str, repo: str, head: str) -> str | None:
    p = cite.strip().strip("`'\"").removeprefix("./")
    if m := COMMIT_RE.match(p):
        return f"https://github.com/{repo}/commit/{m['sha']}"
    if m := LINE_RE.match(p):
        anchor = f"L{m['start']}" + (f"-L{m['end']}" if m["end"] else "")
        return f"https://github.com/{repo}/blob/{head}/{m['path']}#{anchor}"
    return None


def cite_link(cite: str, repo: str, head: str) -> str:
    """`path:line` or `commit:sha` (several allowed) as markdown links."""
    links = []
    for p in (p.strip().strip("`'\"").removeprefix("./") for p in re.split(r"[,;|]", cite)):
        if url := _url(p, repo, head):
            label = f"commit {COMMIT_RE.match(p)['sha'][:7]}" if p.startswith("commit:") else p
            links.append(f"[{label}]({url})")
        elif p:
            links.append(f"`{p}`")
    return ", ".join(links)


def _risk_label(module: dict, top_risk: float) -> str:
    share = module["risk"] / top_risk if top_risk else 0
    return "HIGH" if share >= 0.5 else "MEDIUM" if share >= 0.15 else "LOW"


def module_section(analysis: dict, module: dict, notes: list[dict], reduced: dict, dev_name: str, top_risk: float) -> str:
    """One module's KT section. `notes` are the validated map notes of its files, in file order."""
    repo, head = analysis["repo"], analysis["head"]
    succ = module.get("successor")
    succ_txt = f"@{_name(analysis, succ['dev'])}" if succ else "none, so pick someone and pair early"
    out = [
        f"## {module['path']}",
        f"**Risk: {_risk_label(module, top_risk)}** · {module.get('orphaned_files', 0)} orphaned / "
        f"{module.get('at_risk_files', len(module['files']))} at-risk files · successor: {succ_txt}",
        "",
        "### What it does",
        reduced.get("summary") or "\n".join(f"- `{n['path']}`: {n['purpose']}" for n in notes if n.get("purpose")),
    ]

    def cited(title: str, key: str, label: str):
        rows = [item for n in notes for item in n.get(key, [])]
        out.extend(["", f"### {title}"])
        if not rows:
            out.append("_Nothing verified in the evidence._")
        for item in rows:
            out.append(f"- {item.get(label) or item.get('claim') or item.get('name')} ({cite_link(str(item['cite']), repo, head)})")

    out.extend(["", "### How to work in it"])
    entry_rows = [
        f"- `{n['path']}`: " + ", ".join(f"[`{i['name']}`]({_url(i['cite'], repo, head)})" for i in n["key_entry_points"])
        for n in notes if n.get("key_entry_points")
    ]
    out.extend(entry_rows or ["_Nothing verified in the evidence._"])
    cited("Invariants you must not break", "invariants", "claim")
    cited("Known landmines", "gotchas", "claim")

    def checklist(title: str, items: list[str]):
        out.extend(["", f"### {title}"])
        out.extend([f"- [ ] {i}" for i in items] or ["_None._"])

    checklist(f"Questions to ask {dev_name} before they leave",
              reduced.get("questions") or [q for n in notes for q in n.get("open_questions", [])])
    checklist("Suggested handoff tasks", reduced.get("tasks") or [])
    return "\n".join(out)


def kt_markdown(analysis: dict, dev_id: str, sections: list[str], claims_total: int, claims_verified: int, model: str) -> str:
    dep = analysis.get("departure") or {}
    tf = analysis["truck_factor"]["value"]
    name = _name(analysis, dev_id)
    head = [
        f"# Knowledge-transfer plan: {name}",
        "",
        f"Repository **{analysis['repo']}** at `{analysis['head'][:8]}`. Generated by Handoff with `{model}`.",
        "",
        "| If they leave | |",
        "|---|---|",
        f"| Files that lose their only expert (orphaned) | **{dep.get('orphaned_files', '?')}** |",
        f"| Files where they are an author (at risk) | {dep.get('at_risk_files', '?')} |",
        f"| File coverage | {dep.get('coverage_before', 0):.0%} → **{dep.get('coverage_after', 0):.0%}** |",
        f"| Truck factor | {tf} → **{dep.get('truck_factor_after', '?')}** |",
        f"| Claims verified against the evidence | **{claims_verified} / {claims_total}** |",
        "",
        "Every claim below cites a line or commit we showed the model. Claims that cited anything else were dropped. "
        "Authorship history is an estimate of knowledge concentration, not proof of understanding.",
    ]
    return "\n".join(head) + "\n\n" + "\n\n".join(sections) + "\n"
